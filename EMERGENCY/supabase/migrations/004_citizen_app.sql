-- ---------------------------------------------------------------- 2. incident columns

alter table public.emergency_incidents
    add column if not exists location_source text
        check (location_source is null or location_source in ('gps', 'manual', 'none'));

-- Generated by the app once per report. A retry after a network failure reuses it, so the
-- report is stored once and the app can look it up to confirm instead of guessing.
alter table public.emergency_incidents
    add column if not exists client_request_id uuid;
create unique index if not exists emergency_incidents_client_request_idx
    on public.emergency_incidents (client_request_id) where client_request_id is not null;

-- ---------------------------------------------------------------- 3. citizen insert guard

create or replace function public.citizen_incident_guard()
returns trigger language plpgsql security definer set search_path = public as $$
declare
    recent int;
begin
    -- Dispatcher/server inserts use the service role (auth.uid() is null): leave them alone.
    if auth.uid() is null or new.reporter_id is distinct from auth.uid() then
        return new;
    end if;

    -- Priority and verification are decided by dispatchers, never by the reporting phone.
    new.priority := null;
    new.location_verified := false;

    -- Serialize this citizen's inserts so the checks below can't be raced.
    perform pg_advisory_xact_lock(hashtext('citizen_incident:' || auth.uid()::text));

    if new.client_request_id is not null and exists (
        select 1 from emergency_incidents where client_request_id = new.client_request_id
    ) then
        return new;  -- the unique index rejects it; the app then fetches the stored report
    end if;

    if exists (
        select 1 from emergency_incidents
        where reporter_id = auth.uid()
          and emergency_type = new.emergency_type
          and created_at > now() - interval '60 seconds'
    ) then
        raise exception 'A report of this type was just sent from your account. Check My Reports before sending another.'
            using errcode = 'P0001', hint = 'duplicate_report';
    end if;

    select count(*) into recent from emergency_incidents
    where reporter_id = auth.uid() and created_at > now() - interval '10 minutes';
    if recent >= 3 then
        raise exception 'Too many reports in 10 minutes from this account. Call the emergency hotline directly.'
            using errcode = 'P0001', hint = 'rate_limited';
    end if;

    return new;
end;
$$;

drop trigger if exists emergency_incidents_citizen_guard on public.emergency_incidents;
create trigger emergency_incidents_citizen_guard
    before insert on public.emergency_incidents
    for each row execute function public.citizen_incident_guard();

-- ---------------------------------------------------------------- 4. announcements read path

-- Mirrors app/announcements.py: is_publicly_visible() for a citizen viewer and sort_for_viewer().
-- A citizen sees all_citizens posts plus barangay posts for their barangay. The barangay saved on
-- the account wins over the one picked in the app (same as viewer_context()).
-- Personnel and group-targeted posts are never returned. Drafts, archived, future scheduled and
-- expired posts are filtered out by the publication window.
create or replace function public.citizen_announcements(p_barangay text default null)
returns table (
    id uuid, title text, message text, category text, priority text, target_audience text,
    barangay text, is_pinned boolean, published_at timestamptz, expires_at timestamptz, updated_at timestamptz
)
language sql stable security definer set search_path = public as $$
    with viewer as (
        select coalesce(
            nullif(btrim((select u.raw_user_meta_data ->> 'barangay' from auth.users u where u.id = auth.uid())), ''),
            nullif(btrim(left(p_barangay, 100)), '')
        ) as brgy
    )
    select a.id, a.title, a.message, a.category, a.priority, a.target_audience,
           a.barangay, a.is_pinned, a.published_at, a.expires_at, a.updated_at
    from public.announcements a, viewer v
    where auth.uid() is not null
      and a.status in ('active', 'scheduled')
      and a.published_at is not null and a.published_at <= now()
      and (a.expires_at is null or a.expires_at > now())
      and (
          a.target_audience = 'all_citizens'
          or (a.target_audience = 'barangay' and v.brgy is not null
              and lower(btrim(a.barangay)) = lower(v.brgy))
      )
    order by a.is_pinned desc,
             case a.priority when 'critical' then 0 when 'high' then 1 when 'medium' then 2 when 'low' then 3 else 9 end,
             a.published_at desc
    limit 200;
$$;

revoke all on function public.citizen_announcements(text) from public, anon;
grant execute on function public.citizen_announcements(text) to authenticated;

