-- ESRMS Citizen Emergency App support. Run in Supabase Dashboard -> SQL Editor of the SAME
-- project the Dispatcher Dashboard uses, after 003_dispatch.sql.
-- Lives with the dashboard's migrations so schema.sql, 002, 003 and 004 are applied as one set.
-- Additive and safe to re-run: no table is dropped and no existing row is changed.
--
-- What this adds:
--   1. users.role accepts 'citizen' (the dashboard's register_citizen form already sends it).
--   2. emergency_incidents.location_source and client_request_id (retry-safe submissions).
--   3. A guard trigger on citizen inserts: rate limit, duplicate block, dispatcher-only fields cleared.
--   4. public.citizen_announcements(): the Citizen App's read path for announcements. It applies
--      the same publication-window and audience rules as Flask's /api/announcements/public, so
--      the announcements table itself stays closed to the public key.
--
-- The existing RLS policies from 003_dispatch.sql are unchanged: a signed-in citizen may INSERT a
-- 'new' report as themselves and SELECT only their own reports. No update or delete for citizens.

